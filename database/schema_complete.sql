-- ============================================================
-- 1. TABLE: USERS
-- ============================================================
CREATE TABLE USERS (
    ID                     VARCHAR(36) NOT NULL,
    USERNAME               VARCHAR(50) NOT NULL,
    PASSWORD_HASH          VARCHAR(255) NOT NULL,
    ROLE                   VARCHAR(50) DEFAULT 'USER' NOT NULL,
    IS_ACTIVE              CHAR(1) DEFAULT 'O' NOT NULL,
    CREATED_AT             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CAN_SEE_ALL_CAISSES    CHAR(1) DEFAULT 'O',
    CAN_CREATE             CHAR(1) DEFAULT 'O',
    CAN_UPDATE             CHAR(1) DEFAULT 'O',
    CAN_DELETE             CHAR(1) DEFAULT 'O',
    CAN_MANAGE_COMPTES     CHAR(1) DEFAULT 'N',
    CAN_CREATE_MOV         CHAR(1) DEFAULT 'O',
    CAN_UPDATE_MOV         CHAR(1) DEFAULT 'O',
    CAN_DELETE_MOV         CHAR(1) DEFAULT 'O',
    CAN_VIEW_JOURNAL_SUPPR CHAR(1) DEFAULT 'N',
    CAN_VIEW_OLD_SOLDE     CHAR(1) DEFAULT 'O',
    CAN_VIEW_CUSTOMERS     CHAR(1) DEFAULT 'O',
    CAN_VIEW_PRODUCTS      CHAR(1) DEFAULT 'O',
    CAN_VIEW_SALES         CHAR(1) DEFAULT 'O',
    CAN_VIEW_PURCHASES     CHAR(1) DEFAULT 'O',
    CAN_VIEW_STOCK         CHAR(1) DEFAULT 'O',
    CAN_VIEW_ACCOUNTING    CHAR(1) DEFAULT 'O',
    CAN_VALIDATE_TRANSFERT CHAR(1) DEFAULT 'O',
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME)
);

-- ============================================================
-- 2. TABLE: COMPTES (Plan Comptable & Représentation Intervallaire BG/BD)
-- ============================================================
CREATE TABLE COMPTES (
    ID          VARCHAR(36) NOT NULL,
    CODE        VARCHAR(20) NOT NULL,
    LIBELLE     VARCHAR(100) NOT NULL,
    PARENT_ID   VARCHAR(36),
    NIVEAU      INTEGER DEFAULT 1 NOT NULL,
    IS_ACTIVE   CHAR(1) DEFAULT 'O' NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    COMPTE_FR   VARCHAR(100),
    BG          INTEGER,
    BD          INTEGER,
    USER_ID     VARCHAR(36),
    TYPE_COMPTE VARCHAR(30),
    CONSTRAINT PK_COMPTES PRIMARY KEY (ID),
    CONSTRAINT UQ_COMPTES_CODE UNIQUE (CODE),
    CONSTRAINT FK_COMPTES_PARENT FOREIGN KEY (PARENT_ID) REFERENCES COMPTES (ID)
);

-- ============================================================
-- 3. TABLE: USER_CAISSE_ACCESS (Permissions spécifiques par caisse)
-- ============================================================
CREATE TABLE USER_CAISSE_ACCESS (
    ID         VARCHAR(36) NOT NULL,
    USER_ID    VARCHAR(36) NOT NULL,
    COMPTE_ID  VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_USER_CAISSE_ACCESS PRIMARY KEY (ID),
    CONSTRAINT UQ_UCA_USER_COMPTE UNIQUE (USER_ID, COMPTE_ID),
    CONSTRAINT FK_UCA_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_UCA_COMPTE FOREIGN KEY (COMPTE_ID) REFERENCES COMPTES (ID) ON DELETE CASCADE
);

-- ============================================================
-- 4. TABLE: TYPE_TIERS
-- ============================================================
CREATE TABLE TYPE_TIERS (
    ID   INTEGER NOT NULL,
    TYPE VARCHAR(50) NOT NULL,
    CONSTRAINT PK_TYPE_TIERS PRIMARY KEY (ID)
);

-- ============================================================
-- 5. TABLE: TIERS (Clients et Fournisseurs)
-- ============================================================
CREATE TABLE TIERS (
    ID             VARCHAR(36) NOT NULL,
    ID_TYPE_CLIENT INTEGER NOT NULL,
    NOM            VARCHAR(100) NOT NULL,
    RC             VARCHAR(50),
    NIF            VARCHAR(50),
    AI             VARCHAR(50),
    NIS            VARCHAR(50),
    ADRESSE        VARCHAR(200),
    TELEPHONE      VARCHAR(50),
    EMAIL          VARCHAR(100),
    USER_ID        VARCHAR(36) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TIERS PRIMARY KEY (ID)
);

-- ============================================================
-- 6. TABLE: MOVEMENTS_TRISOIR (Mouvements de Trésorerie)
-- ============================================================
CREATE TABLE MOVEMENTS_TRISOIR (
    ID               VARCHAR(36) NOT NULL,
    DATE_MOV         TIMESTAMP NOT NULL,
    COMPTE_SOURCE_ID VARCHAR(36) NOT NULL,
    COMPTE_DEST_ID   VARCHAR(36) NOT NULL,
    MONTANT          DOUBLE PRECISION NOT NULL,
    DESIGNATION      VARCHAR(500),
    USER_ID          VARCHAR(36) NOT NULL,
    CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_MOVEMENTS_TRISOIR PRIMARY KEY (ID)
);

-- ============================================================
-- 7. TABLE: FACTURE_VENTE
-- ============================================================
CREATE TABLE FACTURE_VENTE (
    ID           VARCHAR(36) NOT NULL,
    TIERS_ID     VARCHAR(36) NOT NULL,
    NUM_FACTURE  VARCHAR(50) NOT NULL,
    DATE_FACTURE TIMESTAMP NOT NULL,
    MONTANT      DOUBLE PRECISION NOT NULL,
    DESIGNATION  VARCHAR(500),
    USER_ID      VARCHAR(36) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_FACTURE_VENTE PRIMARY KEY (ID)
);

-- ============================================================
-- 8. TABLE: FACTURE_ACHAT
-- ============================================================
CREATE TABLE FACTURE_ACHAT (
    ID           VARCHAR(36) NOT NULL,
    TIERS_ID     VARCHAR(36) NOT NULL,
    NUM_FACTURE  VARCHAR(50) NOT NULL,
    DATE_FACTURE TIMESTAMP NOT NULL,
    MONTANT      DOUBLE PRECISION NOT NULL,
    DESIGNATION  VARCHAR(500),
    USER_ID      VARCHAR(36) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_FACTURE_ACHAT PRIMARY KEY (ID)
);

-- ============================================================
-- 9. TABLE: JOURNAL_SUPPRESSION (Audit trail des suppressions)
-- ============================================================
CREATE TABLE JOURNAL_SUPPRESSION (
    ID               VARCHAR(36) NOT NULL,
    DATE_SUPPRESSION TIMESTAMP NOT NULL,
    USER_SUPPRESSION VARCHAR(36),
    MOV_ID           VARCHAR(36) NOT NULL,
    MOV_DATE         TIMESTAMP NOT NULL,
    MOV_MONTANT      NUMERIC(15, 2) NOT NULL,
    MOV_DESIGNATION  VARCHAR(500),
    MOV_SOURCE_ID    VARCHAR(36),
    MOV_DEST_ID      VARCHAR(36),
    MOV_SOURCE_CODE  VARCHAR(50),
    MOV_SOURCE_LIB   VARCHAR(200),
    MOV_DEST_CODE    VARCHAR(50),
    MOV_DEST_LIB     VARCHAR(200),
    CONSTRAINT PK_JOURNAL_SUPP PRIMARY KEY (ID)
);

-- ============================================================
-- 10. TABLE: DEMANDES_TRANSFERT (Demandes de transfert de trésorerie)
-- ============================================================
CREATE TABLE DEMANDES_TRANSFERT (
    ID                  VARCHAR(36) NOT NULL,
    DATE_DEMANDE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    USER_DEMANDEUR_ID   VARCHAR(36) NOT NULL,
    COMPTE_SOURCE_ID    VARCHAR(36) NOT NULL,
    COMPTE_DEST_ID      VARCHAR(36) NOT NULL,
    MONTANT             DOUBLE PRECISION NOT NULL,
    DESIGNATION         VARCHAR(500),
    STATUT              VARCHAR(20) DEFAULT 'EN_ATTENTE' NOT NULL,
    USER_VALIDEUR_ID    VARCHAR(36),
    DATE_VALIDATION     TIMESTAMP,
    MOTIF_REFUS         VARCHAR(500),
    MOVEMENT_ID         VARCHAR(36),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_DEMANDES_TRANSFERT PRIMARY KEY (ID),
    CONSTRAINT FK_DEMANDE_USER_DEM FOREIGN KEY (USER_DEMANDEUR_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_DEMANDE_SRC FOREIGN KEY (COMPTE_SOURCE_ID) REFERENCES COMPTES(ID),
    CONSTRAINT FK_DEMANDE_DEST FOREIGN KEY (COMPTE_DEST_ID) REFERENCES COMPTES(ID)
);

COMMIT;

