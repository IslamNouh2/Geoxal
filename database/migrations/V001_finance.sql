CREATE TABLE COMPTES (
  ID VARCHAR(36) NOT NULL,
  CODE VARCHAR(20) NOT NULL,
  LIBELLE VARCHAR(100) NOT NULL,
  PARENT_ID VARCHAR(36),
  NIVEAU INT DEFAULT 1 NOT NULL,
  IS_ACTIVE CHAR(1) DEFAULT 'O' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_COMPTES PRIMARY KEY (ID),
  CONSTRAINT UQ_COMPTES_CODE UNIQUE (CODE),
  CONSTRAINT FK_COMPTES_PARENT FOREIGN KEY (PARENT_ID) REFERENCES COMPTES (ID)
);

CREATE TABLE MOVEMENTS_TRISOIR (
  ID VARCHAR(36) NOT NULL,
  DATE_MOV TIMESTAMP NOT NULL,
  LIBELLE VARCHAR(200) NOT NULL,
  USER_ID VARCHAR(36),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_MOVEMENTS_TRISOIR PRIMARY KEY (ID)
);

CREATE TABLE DETAILS_MOVEMENTS_TRISOIR (
  ID VARCHAR(36) NOT NULL,
  MOVEMENT_ID VARCHAR(36) NOT NULL,
  COMPTE_ID VARCHAR(36) NOT NULL,
  SENS CHAR(1) NOT NULL,
  LIBELLE VARCHAR(200),
  MONTANT DECIMAL(18, 2) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_DETAILS_MOVEMENTS_TRISOIR PRIMARY KEY (ID),
  CONSTRAINT FK_DETAIL_MOV_MOVEMENT FOREIGN KEY (MOVEMENT_ID) REFERENCES MOVEMENTS_TRISOIR (ID),
  CONSTRAINT FK_DETAIL_MOV_COMTE FOREIGN KEY (COMPTE_ID) REFERENCES COMPTES (ID)
);

