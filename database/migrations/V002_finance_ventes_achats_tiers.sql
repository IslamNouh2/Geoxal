CREATE TABLE TYPE_TIERS (
  ID INT NOT NULL PRIMARY KEY,
  TYPE VARCHAR(50) NOT NULL
);

INSERT INTO TYPE_TIERS (ID, TYPE) VALUES (1, 'Client');
INSERT INTO TYPE_TIERS (ID, TYPE) VALUES (2, 'Fournisseur');

CREATE TABLE TIERS (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  ID_TYPE_CLIENT INT NOT NULL,
  NOM VARCHAR(100) NOT NULL,
  RC VARCHAR(50),
  NIF VARCHAR(50),
  AI VARCHAR(50),
  NIS VARCHAR(50),
  ADRESSE VARCHAR(200),
  TELEPHONE VARCHAR(50),
  EMAIL VARCHAR(100),
  USER_ID VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_TIERS_TYPE FOREIGN KEY (ID_TYPE_CLIENT) REFERENCES TYPE_TIERS (ID),
  CONSTRAINT FK_TIERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE FACTURE_ACHAT (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  TIERS_ID VARCHAR(36) NOT NULL,
  NUM_FACTURE VARCHAR(50) NOT NULL,
  DATE_FACTURE TIMESTAMP NOT NULL,
  MONTANT DOUBLE PRECISION NOT NULL,
  DESIGNATION VARCHAR(500),
  USER_ID VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_FA_TIERS FOREIGN KEY (TIERS_ID) REFERENCES TIERS (ID),
  CONSTRAINT FK_FA_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE FACTURE_VENTE (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  TIERS_ID VARCHAR(36) NOT NULL,
  NUM_FACTURE VARCHAR(50) NOT NULL,
  DATE_FACTURE TIMESTAMP NOT NULL,
  MONTANT DOUBLE PRECISION NOT NULL,
  DESIGNATION VARCHAR(500),
  USER_ID VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_FV_TIERS FOREIGN KEY (TIERS_ID) REFERENCES TIERS (ID),
  CONSTRAINT FK_FV_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

CREATE TABLE MOVEMENTS_TRISOIR (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  DATE_MOV TIMESTAMP NOT NULL,
  COMPTE_SOURCE_ID VARCHAR(36) NOT NULL,
  COMPTE_DEST_ID VARCHAR(36) NOT NULL,
  MONTANT DOUBLE PRECISION NOT NULL,
  DESIGNATION VARCHAR(500),
  USER_ID VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_MOV_SRC FOREIGN KEY (COMPTE_SOURCE_ID) REFERENCES COMPTES (ID),
  CONSTRAINT FK_MOV_DST FOREIGN KEY (COMPTE_DEST_ID) REFERENCES COMPTES (ID),
  CONSTRAINT FK_MOV_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);
