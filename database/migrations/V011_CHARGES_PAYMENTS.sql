CREATE TABLE CHARGES (
    ID_CHARGE VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,

    DATE_CREAT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DATE_MODIF TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    REF_CHARGE VARCHAR(50) NOT NULL,
    DATE_CHARGE DATE DEFAULT CURRENT_DATE NOT NULL,

    COMPTE_ID VARCHAR(36) NOT NULL,

    CATEGORIE_CHARGE VARCHAR(30) NOT NULL,

    CURRENCY_CODE VARCHAR(3) DEFAULT 'DZD' NOT NULL,
    TAUX_CHANGE NUMERIC(18,6) DEFAULT 1.000000 NOT NULL,

    OK_AMORTISSABLE CHAR(1) DEFAULT 'N' NOT NULL,

    DATE_DEBUT_CONSOMMATION DATE,
    DATE_FIN_CONSOMMATION DATE,

    DATE_DEBUT_AMORTISSEMENT DATE,
    DATE_FIN_AMORTISSEMENT DATE,
    ID_MVT_TRESOR VARCHAR(36),

    OBSERVATION VARCHAR(1000),

    MONTANT_CHARGE NUMERIC(18,2) NOT NULL,
    MONTANT_REGLE NUMERIC(18,2) DEFAULT 0.00 NOT NULL,

    DESIGNATION VARCHAR(100) NOT NULL,

    NET_A_PAYER COMPUTED BY (
        MONTANT_CHARGE
    ),

    RESTE_A_REGLER COMPUTED BY (
        MONTANT_CHARGE - MONTANT_REGLE
    ),

    CONSTRAINT PK_CHARGES
        PRIMARY KEY (ID_CHARGE),

    CONSTRAINT CK_CHARGE_MONTANT
        CHECK (MONTANT_CHARGE > 0),

    CONSTRAINT CK_CHARGE_REGLE
        CHECK (
            MONTANT_REGLE >= 0
            AND MONTANT_REGLE <= MONTANT_CHARGE
        ),

    CONSTRAINT CK_CHARGE_TAUX
        CHECK (TAUX_CHANGE > 0),

    CONSTRAINT CK_CHARGE_AMORT
        CHECK (OK_AMORTISSABLE IN ('O', 'N')),

    CONSTRAINT CK_CHARGE_CATEGORIE
        CHECK (
            CATEGORIE_CHARGE IN (
                'SIMPLE',
                'AMORTISSABLE'
            )
        ),

    CONSTRAINT CK_CHARGE_DATES
        CHECK (
            (
                CATEGORIE_CHARGE = 'SIMPLE'
                AND OK_AMORTISSABLE = 'N'
                AND DATE_DEBUT_CONSOMMATION IS NOT NULL
                AND DATE_FIN_CONSOMMATION IS NOT NULL
                AND DATE_FIN_CONSOMMATION >= DATE_DEBUT_CONSOMMATION
                AND DATE_DEBUT_AMORTISSEMENT IS NULL
                AND DATE_FIN_AMORTISSEMENT IS NULL
            )
            OR
            (
                CATEGORIE_CHARGE = 'AMORTISSABLE'
                AND OK_AMORTISSABLE = 'O'
                AND DATE_DEBUT_AMORTISSEMENT IS NOT NULL
                AND DATE_FIN_AMORTISSEMENT IS NOT NULL
                AND DATE_FIN_AMORTISSEMENT >= DATE_DEBUT_AMORTISSEMENT
                AND DATE_DEBUT_CONSOMMATION IS NULL
                AND DATE_FIN_CONSOMMATION IS NULL
            )
        )
);

