CREATE TABLE DETAIL_MVT_CHARGES (
    ID_DETAIL_MVT_CHARGE VARCHAR(36) NOT NULL,

    ID_MVT_TRESOR VARCHAR(36) NOT NULL,

    TRANCHE_MONTANT NUMERIC(18,2) NOT NULL,

    ID_CHARGE VARCHAR(36) NOT NULL,

    DATE_CREAT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_DETAIL_MVT_CHARGES
        PRIMARY KEY (ID_DETAIL_MVT_CHARGE),

    CONSTRAINT FK_DMC_CHARGE
        FOREIGN KEY (ID_CHARGE)
        REFERENCES CHARGES (ID_CHARGE),

    CONSTRAINT FK_DMC_MOUVEMENT
        FOREIGN KEY (ID_MVT_TRESOR)
        REFERENCES MOVEMENTS_TRISOIR (ID),

    CONSTRAINT CK_DMC_MONTANT
        CHECK (TRANCHE_MONTANT > 0),

    CONSTRAINT UQ_DMC_MOUVEMENT
        UNIQUE (ID_MVT_TRESOR)
);

-- @statement
CREATE EXCEPTION EX_CHARGE_PAYMENT_INVALID
'Invalid charge payment';

-- @statement
CREATE EXCEPTION EX_CHARGE_PAYMENT_EXCEEDED
'Payment exceeds remaining charge amount';

-- @statement
CREATE OR ALTER TRIGGER TRG_CHARGES_BI
FOR CHARGES
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.CATEGORIE_CHARGE = 'AMORTISSABLE') THEN
    BEGIN
        NEW.DATE_DEBUT_AMORTISSEMENT =
            CAST(NEW.DATE_CREAT AS DATE);

        NEW.DATE_DEBUT_CONSOMMATION = NULL;
        NEW.DATE_FIN_CONSOMMATION = NULL;
    END
END

-- @statement
CREATE OR ALTER TRIGGER TRG_CHARGES_BU
FOR CHARGES
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.DATE_MODIF = CURRENT_TIMESTAMP;

    IF (NEW.MONTANT_CHARGE < OLD.MONTANT_REGLE) THEN
        EXCEPTION EX_CHARGE_PAYMENT_INVALID;
END

-- @statement
CREATE OR ALTER TRIGGER TRG_DMC_BI
FOR DETAIL_MVT_CHARGES
ACTIVE BEFORE INSERT POSITION 0
AS
DECLARE VARIABLE V_TOTAL NUMERIC(18,2);
DECLARE VARIABLE V_CHARGE NUMERIC(18,2);
BEGIN
    SELECT C.MONTANT_CHARGE
    FROM CHARGES C
    WHERE C.ID_CHARGE = NEW.ID_CHARGE
    INTO :V_CHARGE;

    IF (V_CHARGE IS NULL) THEN
        EXCEPTION EX_CHARGE_PAYMENT_INVALID;

    SELECT COALESCE(SUM(D.TRANCHE_MONTANT), 0)
    FROM DETAIL_MVT_CHARGES D
    WHERE D.ID_CHARGE = NEW.ID_CHARGE
    INTO :V_TOTAL;

    IF (V_TOTAL + NEW.TRANCHE_MONTANT > V_CHARGE) THEN
        EXCEPTION EX_CHARGE_PAYMENT_EXCEEDED;
END

-- @statement
CREATE OR ALTER TRIGGER TRG_DMC_BU
FOR DETAIL_MVT_CHARGES
ACTIVE BEFORE UPDATE POSITION 0
AS
DECLARE VARIABLE V_TOTAL NUMERIC(18,2);
DECLARE VARIABLE V_CHARGE NUMERIC(18,2);
BEGIN
    SELECT C.MONTANT_CHARGE
    FROM CHARGES C
    WHERE C.ID_CHARGE = NEW.ID_CHARGE
    INTO :V_CHARGE;

    IF (V_CHARGE IS NULL) THEN
        EXCEPTION EX_CHARGE_PAYMENT_INVALID;

    SELECT COALESCE(SUM(D.TRANCHE_MONTANT), 0)
    FROM DETAIL_MVT_CHARGES D
    WHERE D.ID_CHARGE = NEW.ID_CHARGE
      AND D.ID_DETAIL_MVT_CHARGE <> OLD.ID_DETAIL_MVT_CHARGE
    INTO :V_TOTAL;

    IF (V_TOTAL + NEW.TRANCHE_MONTANT > V_CHARGE) THEN
        EXCEPTION EX_CHARGE_PAYMENT_EXCEEDED;
END

-- @statement
CREATE OR ALTER TRIGGER TRG_DMC_AI
FOR DETAIL_MVT_CHARGES
ACTIVE AFTER INSERT POSITION 0
AS
BEGIN
    UPDATE CHARGES C
    SET MONTANT_REGLE = (
        SELECT COALESCE(SUM(D.TRANCHE_MONTANT), 0)
        FROM DETAIL_MVT_CHARGES D
        WHERE D.ID_CHARGE = NEW.ID_CHARGE
    )
    WHERE C.ID_CHARGE = NEW.ID_CHARGE;
END

-- @statement
CREATE OR ALTER TRIGGER TRG_DMC_AU
FOR DETAIL_MVT_CHARGES
ACTIVE AFTER UPDATE POSITION 0
AS
BEGIN
    UPDATE CHARGES C
    SET MONTANT_REGLE = (
        SELECT COALESCE(SUM(D.TRANCHE_MONTANT), 0)
        FROM DETAIL_MVT_CHARGES D
        WHERE D.ID_CHARGE = OLD.ID_CHARGE
    )
    WHERE C.ID_CHARGE = OLD.ID_CHARGE;

    IF (NEW.ID_CHARGE <> OLD.ID_CHARGE) THEN
    BEGIN
        UPDATE CHARGES C
        SET MONTANT_REGLE = (
            SELECT COALESCE(SUM(D.TRANCHE_MONTANT), 0)
            FROM DETAIL_MVT_CHARGES D
            WHERE D.ID_CHARGE = NEW.ID_CHARGE
        )
        WHERE C.ID_CHARGE = NEW.ID_CHARGE;
    END
END

