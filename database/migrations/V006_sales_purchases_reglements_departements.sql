-- Departments table
CREATE TABLE DEPARTEMENT (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    CODE VARCHAR(50) NOT NULL,
    NOM VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255),
    IS_ACTIVE CHAR(1) DEFAULT 'O' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- App Parameters / Settings table
CREATE TABLE APP_SETTINGS (
    SETTING_KEY VARCHAR(100) NOT NULL PRIMARY KEY,
    SETTING_VALUE VARCHAR(255),
    DESCRIPTION VARCHAR(255)
);

-- Reglements (Payments & Receipts)
CREATE TABLE REGLEMENT (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    NUM_REGLEMENT VARCHAR(50) NOT NULL,
    TYPE_REGLEMENT VARCHAR(20) NOT NULL, -- 'CLIENT' ou 'FOURNISSEUR'
    TIERS_ID VARCHAR(36) NOT NULL,
    COMPTE_CAISSE_ID VARCHAR(36) NOT NULL,
    COMPTE_CONTREPARTIE_ID VARCHAR(36),
    DATE_REGLEMENT TIMESTAMP NOT NULL,
    MONTANT DOUBLE PRECISION NOT NULL,
    MODE_PAIEMENT VARCHAR(30) NOT NULL,
    DEPARTEMENT_ID VARCHAR(36),
    NUM_CHEQUE VARCHAR(50),
    DATE_CHEQUE TIMESTAMP,
    OBSERVATION VARCHAR(500),
    MOVEMENT_TRISOR_ID VARCHAR(36),
    USER_ID VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Reglement to Facture allocation table
CREATE TABLE REGLEMENT_FACTURE (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    REGLEMENT_ID VARCHAR(36) NOT NULL,
    FACTURE_TYPE VARCHAR(20) NOT NULL, -- 'VENTE' ou 'ACHAT'
    FACTURE_ID VARCHAR(36) NOT NULL,
    MONTANT_APPLIQUE DOUBLE PRECISION NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

