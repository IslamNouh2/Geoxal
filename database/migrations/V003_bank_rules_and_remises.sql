-- ============================================================
-- V003_bank_rules_and_remises.sql
-- Module Trésorerie: Règles bancaires, Remise de chèques et Frais
-- Compatible Firebird Dialect 1 & 3
-- 
-- RÈGLE D'ARCHITECTURE:
-- Aucune table superflue 'BANKS' ou 'BANK_ACCOUNTS' ou 'CHARGE_TYPES'.
-- Toutes les banques, comptes bancaires, taxes (TVA) et charges 
-- SONT DIRECTEMENT DES COMPTES dans la table existante 'COMPTES'.
-- ============================================================

-- 1. TABLE: TRANSACTION_TYPES (Types d'opérations bancaires configurables)
CREATE TABLE TRANSACTION_TYPES (
    ID          VARCHAR(36) NOT NULL PRIMARY KEY,
    CODE        VARCHAR(50) NOT NULL,
    LABEL       VARCHAR(100) NOT NULL,
    ACTIVE      CHAR(1) DEFAULT 'O' NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_TX_TYPE_CODE UNIQUE (CODE)
);

-- 2. TABLE: BANK_RULES (Règles de frais bancaires paramétrables)
-- bank_compte_id pointe directement vers un compte de type 'banque' dans COMPTES (NULL = toutes les banques)
-- charge_compte_id pointe directement vers un compte de charges dans COMPTES (ex: 68 Autres charges / Frais bancaires)
-- tax_compte_id pointe directement vers un compte de TVA dans COMPTES (ex: TVA déductible)
CREATE TABLE BANK_RULES (
    ID                   VARCHAR(36) NOT NULL PRIMARY KEY,
    NAME                 VARCHAR(150) NOT NULL,
    ACTIVE               CHAR(1) DEFAULT 'O' NOT NULL,
    PRIORITY             INT DEFAULT 0 NOT NULL,
    BANK_COMPTE_ID       VARCHAR(36),                        -- NULL = Toutes les banques / comptes bancaires
    TRANSACTION_TYPE_ID  VARCHAR(36),                        -- NULL = Tous types de transactions
    CHARGE_COMPTE_ID     VARCHAR(36) NOT NULL,               -- FK COMPTES (compte de charge)
    CALC_METHOD          VARCHAR(30) NOT NULL,               -- FIXED | PERCENT | PERCENT_WITH_MIN_MAX | TIERED | PER_CHEQUE
    AMOUNT               DOUBLE PRECISION DEFAULT 0.0,
    PERCENT_VAL          DOUBLE PRECISION DEFAULT 0.0,
    MIN_AMOUNT           DOUBLE PRECISION DEFAULT 0.0,
    MAX_AMOUNT           DOUBLE PRECISION DEFAULT 0.0,
    BASE_TYPE            VARCHAR(30) DEFAULT 'TRANSACTION_AMOUNT' NOT NULL, -- TRANSACTION_AMOUNT | PARENT_RULE_AMOUNT
    PARENT_RULE_ID       VARCHAR(36),
    TAX_COMPTE_ID        VARCHAR(36),                        -- FK COMPTES (compte TVA)
    TAX_RATE_PERCENT     DOUBLE PRECISION DEFAULT 19.0,      -- Taux modifiable (ex: 19%)
    ROUNDING_MODE        VARCHAR(20) DEFAULT 'ROUND_HALF_UP' NOT NULL,
    VALID_FROM           TIMESTAMP NOT NULL,
    VALID_TO             TIMESTAMP,
    IS_CUMULATIVE        CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_BR_BANK_COMPTE FOREIGN KEY (BANK_COMPTE_ID) REFERENCES COMPTES (ID),
    CONSTRAINT FK_BR_TX_TYPE FOREIGN KEY (TRANSACTION_TYPE_ID) REFERENCES TRANSACTION_TYPES (ID),
    CONSTRAINT FK_BR_CHARGE_COMPTE FOREIGN KEY (CHARGE_COMPTE_ID) REFERENCES COMPTES (ID),
    CONSTRAINT FK_BR_PARENT FOREIGN KEY (PARENT_RULE_ID) REFERENCES BANK_RULES (ID),
    CONSTRAINT FK_BR_TAX_COMPTE FOREIGN KEY (TAX_COMPTE_ID) REFERENCES COMPTES (ID)
);

-- 3. TABLE: REMISES_CHEQUES (Bordereaux de remise de chèques)
-- bank_compte_id est le compte bancaire destinataire dans COMPTES (ex: 512 Banque principale)
CREATE TABLE REMISES_CHEQUES (
    ID                  VARCHAR(36) NOT NULL PRIMARY KEY,
    BORDEREAU_NUMBER    VARCHAR(50) NOT NULL,
    DATE_REMISE         TIMESTAMP NOT NULL,
    BANK_COMPTE_ID      VARCHAR(36) NOT NULL,                -- FK COMPTES
    TOTAL_AMOUNT        DOUBLE PRECISION DEFAULT 0.0 NOT NULL,
    CHEQUES_COUNT       INT DEFAULT 0 NOT NULL,
    STATUS              VARCHAR(20) DEFAULT 'BROUILLON' NOT NULL, -- BROUILLON | VALIDEE | ANNULEE
    NOTES               VARCHAR(500),
    MOVEMENT_TRISOR_ID  VARCHAR(36),
    CREATED_BY          VARCHAR(36) NOT NULL,
    VALIDATED_BY        VARCHAR(36),
    VALIDATED_AT        TIMESTAMP,
    CANCELLED_BY        VARCHAR(36),
    CANCELLED_AT        TIMESTAMP,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_REMISE_NUM UNIQUE (BORDEREAU_NUMBER),
    CONSTRAINT FK_REMISE_BANK_COMPTE FOREIGN KEY (BANK_COMPTE_ID) REFERENCES COMPTES (ID),
    CONSTRAINT FK_REMISE_USER_CR FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_REMISE_USER_VAL FOREIGN KEY (VALIDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_REMISE_MOV FOREIGN KEY (MOVEMENT_TRISOR_ID) REFERENCES MOVEMENTS_TRISOIR (ID)
);

-- 4. TABLE: CHEQUES (Traçabilité complète des chèques)
-- drawee_bank_compte_id pointe vers le compte bancaire de la banque tirée dans COMPTES (ou drawee_bank_name en varchar)
CREATE TABLE CHEQUES (
    ID                     VARCHAR(36) NOT NULL PRIMARY KEY,
    CHEQUE_NUMBER          VARCHAR(50) NOT NULL,
    MONTANT                DOUBLE PRECISION NOT NULL,
    TIERS_ID               VARCHAR(36) NOT NULL,
    DRAWEE_BANK_COMPTE_ID  VARCHAR(36),          -- FK COMPTES si banque répertoriée dans le plan comptable
    DRAWEE_BANK_NAME       VARCHAR(100),         -- Nom / code de la banque tirée (BNA, BADR, Housing Bank, CPA, etc.)
    ISSUE_DATE             TIMESTAMP NOT NULL,
    DUE_DATE               TIMESTAMP,            -- Date d'échéance si chèque postdaté
    FACTURE_VENTE_ID       VARCHAR(36),          -- Lien avec facture de vente
    REMISE_ID              VARCHAR(36),          -- Lien bordereau de remise
    STATUS                 VARCHAR(25) DEFAULT 'EN_PORTEFEUILLE' NOT NULL, -- EN_PORTEFEUILLE | DANS_REMISE | REMIS_EN_BANQUE | ENCAISSE | IMPAYE | ANNULE
    NOTES                  VARCHAR(500),
    USER_ID                VARCHAR(36) NOT NULL,
    CREATED_AT             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CHQ_TIERS FOREIGN KEY (TIERS_ID) REFERENCES TIERS (ID),
    CONSTRAINT FK_CHQ_DRAWEE_COMPTE FOREIGN KEY (DRAWEE_BANK_COMPTE_ID) REFERENCES COMPTES (ID),
    CONSTRAINT FK_CHQ_FV FOREIGN KEY (FACTURE_VENTE_ID) REFERENCES FACTURE_VENTE (ID),
    CONSTRAINT FK_CHQ_REMISE FOREIGN KEY (REMISE_ID) REFERENCES REMISES_CHEQUES (ID),
    CONSTRAINT FK_CHQ_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

-- 5. TABLE: BANK_TRANSACTION_FEES (Snapshot immuable des frais calculés / appliqués)
-- charge_compte_id pointe directement vers COMPTES
CREATE TABLE BANK_TRANSACTION_FEES (
    ID                  VARCHAR(36) NOT NULL PRIMARY KEY,
    REMISE_ID           VARCHAR(36),
    MOVEMENT_TRISOR_ID  VARCHAR(36),
    RULE_ID             VARCHAR(36),
    CHARGE_COMPTE_ID    VARCHAR(36) NOT NULL,                -- FK COMPTES
    BASE_AMOUNT         DOUBLE PRECISION NOT NULL,
    RATE_OR_AMOUNT      DOUBLE PRECISION NOT NULL,
    COMPUTED_AMOUNT     DOUBLE PRECISION NOT NULL,
    FINAL_AMOUNT        DOUBLE PRECISION NOT NULL,
    IS_MANUALLY_EDITED  CHAR(1) DEFAULT 'N' NOT NULL,
    EDITED_BY           VARCHAR(36),
    EDITED_AT           TIMESTAMP,
    EDIT_REASON         VARCHAR(255),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_BTF_REMISE FOREIGN KEY (REMISE_ID) REFERENCES REMISES_CHEQUES (ID),
    CONSTRAINT FK_BTF_MOV FOREIGN KEY (MOVEMENT_TRISOR_ID) REFERENCES MOVEMENTS_TRISOIR (ID),
    CONSTRAINT FK_BTF_RULE FOREIGN KEY (RULE_ID) REFERENCES BANK_RULES (ID),
    CONSTRAINT FK_BTF_CHARGE_COMPTE FOREIGN KEY (CHARGE_COMPTE_ID) REFERENCES COMPTES (ID)
);

-- 6. TABLE: BANK_AUDIT_LOGS (Audit trail des modifications de frais, validation et annulation)
CREATE TABLE BANK_AUDIT_LOGS (
    ID          VARCHAR(36) NOT NULL PRIMARY KEY,
    USER_ID     VARCHAR(36) NOT NULL,
    ACTION      VARCHAR(50) NOT NULL, -- RULE_CREATED | RULE_UPDATED | REMISE_VALIDATED | REMISE_CANCELLED | FEE_MANUALLY_EDITED
    ENTITY_NAME VARCHAR(50) NOT NULL,
    ENTITY_ID   VARCHAR(36) NOT NULL,
    DETAILS     VARCHAR(1000),
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_BAL_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

